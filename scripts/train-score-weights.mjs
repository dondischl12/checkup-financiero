// Fits the 8 pillar-combination weights in src/data/scoreModelWeights.js.
//
// This is a ridge-regularized linear regression, trained with plain-JS batch
// gradient descent (no ML library, no API call) on ~3,000 synthetic household
// profiles from generate-synthetic-households.mjs. The regression starts from
// the published FinHealth pillar weights as its prior and only moves away from
// them as far as the synthetic data supports (the ridge penalty pulls back
// toward the prior), so the result stays close to a documented benchmark
// instead of drifting into an unexplainable set of numbers.
//
// Run: node scripts/train-score-weights.mjs

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { calculatePillarScores } from '../src/lib/financialCalculations.js'
import { generateSyntheticHouseholds } from './generate-synthetic-households.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const PRIOR_WEIGHTS = {
  incomeStability: 12.5,
  spendingDiscipline: 12.5,
  expenseStructure: 20,
  emergencyFund: 20,
  debtBurden: 15,
  insuranceCoverage: 5,
  longTermAssets: 5,
  habitsWellbeing: 10,
}

const KEYS = Object.keys(PRIOR_WEIGHTS)
const HOUSEHOLD_COUNT = 3000

function buildDataset(count) {
  const households = generateSyntheticHouseholds({ count })
  const X = households.map(({ answers }) => {
    const pillars = calculatePillarScores(answers)
    return KEYS.map((key) => pillars[key] / 100)
  })
  const y = households.map((h) => h.latentTarget)
  return { X, y }
}

function trainRidgeGradientDescent(X, y, prior, { lambda = 0.4, learningRate = 0.015, iterations = 4000 } = {}) {
  const n = X.length
  const dims = KEYS.length
  const weights = KEYS.map((key) => prior[key])

  for (let iter = 0; iter < iterations; iter += 1) {
    const grad = new Array(dims).fill(0)
    let squaredError = 0

    for (let i = 0; i < n; i += 1) {
      const predicted = X[i].reduce((sum, xij, j) => sum + weights[j] * xij, 0)
      const error = predicted - y[i]
      squaredError += error * error
      for (let j = 0; j < dims; j += 1) {
        grad[j] += (2 * error * X[i][j]) / n
      }
    }

    for (let j = 0; j < dims; j += 1) {
      const ridgeGrad = 2 * lambda * (weights[j] - prior[KEYS[j]])
      weights[j] -= learningRate * (grad[j] + ridgeGrad)
    }

    if (iter % 500 === 0 || iter === iterations - 1) {
      console.log(`  iter ${String(iter).padStart(4, ' ')}: mse=${(squaredError / n).toFixed(3)}`)
    }
  }

  return weights
}

// Keeps every pillar weight positive (a higher pillar score should never lower the
// total) and rescales so the 8 weights sum to exactly 100, same contract as the
// hand-set weights they replace.
function finalizeWeights(rawWeights) {
  const floored = rawWeights.map((w) => Math.max(1.5, w))
  const sum = floored.reduce((a, b) => a + b, 0)
  return KEYS.reduce((acc, key, i) => {
    acc[key] = Math.round((floored[i] / sum) * 10000) / 100
    return acc
  }, {})
}

function writeWeightsFile(weights, metadata) {
  const contents = `// AUTO-GENERATED by scripts/train-score-weights.mjs — do not hand-edit.
// Regenerate with: node scripts/train-score-weights.mjs
//
// Pillar combination weights for the Katalyst score. Fit with a ridge-regularized
// linear regression (plain-JS gradient descent, no ML library, no API call) on
// synthetic household data — see generate-synthetic-households.mjs for how those
// households and their training target are built. The regression starts from the
// published FinHealth pillar weights as its prior, so it only drifts from that
// benchmark as far as the synthetic data actually supports.
export const PILLAR_WEIGHTS = ${JSON.stringify(weights, null, 2)}

export const TRAINING_METADATA = ${JSON.stringify(metadata, null, 2)}
`
  const outPath = path.join(__dirname, '..', 'src', 'data', 'scoreModelWeights.js')
  writeFileSync(outPath, contents)
  return outPath
}

function main() {
  console.log(`Generating ${HOUSEHOLD_COUNT} synthetic households...`)
  const { X, y } = buildDataset(HOUSEHOLD_COUNT)

  console.log('Training ridge-regularized regression...')
  const rawWeights = trainRidgeGradientDescent(X, y, PRIOR_WEIGHTS)
  const weights = finalizeWeights(rawWeights)

  const metadata = {
    trainedAt: new Date().toISOString(),
    households: HOUSEHOLD_COUNT,
    priorWeights: PRIOR_WEIGHTS,
    note: 'Ridge-regularized linear regression (pure JS gradient descent) fit on synthetic household data; prior = published FinHealth pillar weights.',
  }

  const outPath = writeWeightsFile(weights, metadata)
  console.log('\nFinal weights (sum should be 100):')
  console.table(weights)
  console.log('sum =', Object.values(weights).reduce((a, b) => a + b, 0))
  console.log('\nWrote', outPath)
}

main()
